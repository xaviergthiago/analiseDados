alunos = {"nome":"João", "idade": 18}
print(alunos)  # Saída: {'nome': 'João', 'idade': 18}
print("Chaves", alunos.keys())  # Saída: dict_keys(['nome', 'idade'])
print("Valores", alunos.values())  # Saída: dict_values(['João', 18])
print("Itens", alunos.items())  # Saída: dict_items([('nome', 'João'), ('idade', 18)])